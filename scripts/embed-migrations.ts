// Copies the drizzle migrations into a TypeScript module, so the compiled app (which has no
// `drizzle/` folder next to it) runs the same migrations as the source checkout.
// `bun run db:generate` in packages/app runs this after drizzle-kit; the e2e suite fails when the
// embedded list is behind the folder.
import { join } from "node:path";
import { z } from "zod";

const Journal = z.object({
  entries: z.array(z.object({ tag: z.string(), when: z.number() })),
});

const appDir = join(import.meta.dir, "../packages/app");
const target = join(appDir, "src/store/migrations.generated.ts");

async function entryOf(journalEntry: { tag: string; when: number }): Promise<string> {
  const sql = await Bun.file(join(appDir, "drizzle", `${journalEntry.tag}.sql`)).text();
  return `  {\n    when: ${String(journalEntry.when)},\n    sql: ${JSON.stringify(sql)},\n  },`;
}

const journal = Journal.parse(await Bun.file(join(appDir, "drizzle/meta/_journal.json")).json());
const entries = await Promise.all(journal.entries.map(entryOf));
const header =
  "// Generated by scripts/embed-migrations.ts (run by `db:generate`). Do not edit by hand.\n";
const body = `export const EMBEDDED_MIGRATIONS = [\n${entries.join("\n")}\n] as const;\n`;
await Bun.write(target, `${header}${body}`);
// Biome picks the quote style that needs the fewest escapes, so let it have the last word.
Bun.spawnSync(["bunx", "biome", "format", "--write", target], { cwd: join(appDir, "../..") });
console.log(`embedded ${String(entries.length)} migrations into ${target}`);
